# Writes the SDK's bindings from src/lib.rs's and src/character.rs's exported functions, constants and doc comments:
#   include/delirium_physics.h            C
#   bindings/csharp/Delirium.cs   C# (P/Invoke)
#   bindings/python/delirium_physics.py   Python (ctypes)
# The C++ wrapper (include/delirium_physics.hpp) is by hand over the C header. usage: python -I bindgen.py
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
src = ''.join(open(os.path.join(HERE, 'src', f), encoding='utf-8').read() for f in ('lib.rs', 'character.rs'))

consts = re.findall(r'pub const (NM_\w+): i32 = (-?\d+);', src)
fns = []
for m in re.finditer(r'((?:^///.*\n)*)#\[unsafe\(no_mangle\)\]\npub (?:unsafe )?extern "C" fn (nm_\w+)\(([^)]*)\)(?: -> ([^{]+))? \{', src, re.M):
    doc = ' '.join(l[3:].strip() for l in m.group(1).splitlines())
    args = []
    for a in filter(None, (x.strip() for x in m.group(3).replace('\n', ' ').split(','))):
        n, t = a.split(':', 1)
        args.append((n.strip(), t.strip()))
    fns.append((m.group(2), args, (m.group(4) or '()').strip(), doc))

C = {'i32': 'int32_t', 'f32': 'float', 'u8': 'uint8_t', 'u32': 'uint32_t', 'c_char': 'char', '()': 'void',
     'NmWorld': 'NmWorld', 'NmBuild': 'NmBuild', 'NmAgent': 'NmAgent'}
def ctype(t):
    if t.startswith('*const '): return 'const ' + ctype(t[7:]) + '*'
    if t.startswith('*mut '): return ctype(t[5:]) + '*'
    return C[t]

H = ['/* delirium_physics: the NM (Delirium) port\'s C API. Generated by crates/delirium-sdk/bindgen.py from src/lib.rs; edit that. */',
     '#ifndef DELIRIUM_PHYSICS_H', '#define DELIRIUM_PHYSICS_H', '#include <stdint.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif', '',
     '#if defined(_WIN32) && !defined(DELIRIUM_PHYSICS_STATIC)', '#define NM_API __declspec(dllimport)', '#else', '#define NM_API', '#endif', '',
     'typedef struct NmWorld NmWorld;', 'typedef struct NmBuild NmBuild;', 'typedef struct NmAgent NmAgent;', '']
H += [f'#define {n} ({v})' for n, v in consts] + ['']
for n, args, ret, doc in fns:
    if doc:
        H.append(f'/* {doc} */')
    a = ', '.join(f'{ctype(t)} {an}' for an, t in args) or 'void'
    H.append(f'NM_API {ctype(ret)} {n}({a});')
H += ['', '#ifdef __cplusplus', '}', '#endif', '#endif', '']
os.makedirs(os.path.join(HERE, 'include'), exist_ok=True)
open(os.path.join(HERE, 'include', 'delirium_physics.h'), 'w', newline='\n').write('\n'.join(H))

# C#: handles and buffers as IntPtr / arrays; strings in as UTF-8 (LPUTF8Str), out through byte[].
def cs(t, n):
    if t == 'i32': return 'int'
    if t == 'f32': return 'float'
    if t == '()': return 'void'
    if t in ('*const c_char',): return '[MarshalAs(UnmanagedType.LPUTF8Str)] string'
    if t == '*mut c_char': return 'byte[]'
    if t in ('*const f32', '*mut f32'): return 'float[]'
    if t == '*const u32': return 'uint[]'
    if t == '*const u8': return 'byte[]'
    if t == '*mut i32': return 'out int'
    if t.endswith(('NmWorld', 'NmBuild', 'NmAgent')): return 'IntPtr'
    raise ValueError(t)
CS_KEYWORDS = {'out', 'ref', 'in', 'params', 'string', 'object', 'base', 'event', 'fixed', 'lock'}
S = ['// Delirium: C# bindings of the NM port\'s C API (delirium_physics.dll). Generated by crates/delirium-sdk/bindgen.py; edit that.',
     'using System;', 'using System.Runtime.InteropServices;', 'using System.Text;', '', 'namespace Delirium', '{',
     '    public static class Native', '    {', '        public const string Dll = "delirium_physics";']
S += [f'        public const int {n} = {v};' for n, v in consts]
for n, args, ret, doc in fns:
    if doc:
        S.append(f'        /// <summary>{doc.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")}</summary>')
    S.append('        [DllImport(Dll, CallingConvention = CallingConvention.Cdecl)]')
    rt = 'IntPtr' if ret.startswith('*') else cs(ret, n)
    S.append(f'        public static extern {rt} {n}(' + ', '.join(f'{cs(t, an)} {"@" + an if an in CS_KEYWORDS else an}' for an, t in args) + ');')
S += ['',
      '        /// <summary>A string out of a buffer call (nm_*_name, nm_last_error...).</summary>',
      '        public static string Str(Func<byte[], int, int> call)',
      '        {',
      '            int n = call(null, 0);',
      '            if (n <= 0) return null;',
      '            var b = new byte[n];',
      '            call(b, n);',
      '            return Encoding.UTF8.GetString(b, 0, n - 1);',
      '        }',
      '',
      '        public static string LastError() => Str((b, n) => nm_last_error(b, n));',
      '    }', '}', '']
os.makedirs(os.path.join(HERE, 'bindings', 'csharp'), exist_ok=True)
open(os.path.join(HERE, 'bindings', 'csharp', 'Delirium.cs'), 'w', newline='\n').write('\n'.join(S))
os.makedirs(os.path.join(HERE, 'bindings', 'unity', 'Runtime'), exist_ok=True)
open(os.path.join(HERE, 'bindings', 'unity', 'Runtime', 'Delirium.cs'), 'w', newline=chr(10)).write(chr(10).join(S))

# Python (ctypes): the raw functions plus small helpers; bindings/python/example.py uses them.
def py(t):
    return {'i32': 'c_int32', 'f32': 'c_float', '()': 'None', '*const c_char': 'c_char_p', '*mut c_char': 'c_char_p',
            '*const f32': 'P(c_float)', '*mut f32': 'P(c_float)', '*const u32': 'P(c_uint32)', '*const u8': 'P(c_uint8)',
            '*mut i32': 'P(c_int32)'}.get(t, 'c_void_p')
P = ['"""delirium_physics: Python (ctypes) bindings of the NM port\'s C API. Generated by crates/delirium-sdk/bindgen.py; edit that."""',
     'import ctypes, os, sys',
     'from ctypes import c_int32, c_float, c_uint32, c_uint8, c_char_p, c_void_p, POINTER as P', '',
     'def _load():',
     '    name = {"win32": "delirium_physics.dll", "darwin": "libdelirium_physics.dylib"}.get(sys.platform, "libdelirium_physics.so")',
     '    for d in [os.environ.get("DELIRIUM_PHYSICS_LIB", ""), os.path.dirname(os.path.abspath(__file__))]:',
     '        p = os.path.join(d, name) if d and os.path.isdir(d) else d',
     '        if p and os.path.isfile(p):',
     '            return ctypes.CDLL(p)',
     '    return ctypes.CDLL(name)', '', 'lib = _load()', '']
P += [f'{n} = {v}' for n, v in consts] + ['']
for n, args, ret, doc in fns:
    P.append(f'lib.{n}.argtypes = [' + ', '.join(py(t) for _, t in args) + ']')
    P.append(f'lib.{n}.restype = {py(ret)}')
P += ['',
      'def vec(*xs):',
      '    """A float array (vectors, quaternions) for the calls."""',
      '    return (c_float * len(xs))(*xs)', '',
      'def text(call, *args):',
      '    """A string out of a buffer call: text(lib.nm_message_name, 3)."""',
      '    n = call(*args, None, 0)',
      '    if n <= 0:',
      '        return None',
      '    b = ctypes.create_string_buffer(n)',
      '    call(*args, b, n)',
      '    return b.value.decode()', '',
      'def last_error():',
      '    return text(lib.nm_last_error)', '',
      'def check(r):',
      '    """Raises on a negative return."""',
      '    if isinstance(r, int) and r < 0:',
      '        raise RuntimeError(f"delirium_physics {r}: {last_error()}")',
      '    return r', '']
os.makedirs(os.path.join(HERE, 'bindings', 'python'), exist_ok=True)
open(os.path.join(HERE, 'bindings', 'python', 'delirium_physics.py'), 'w', newline='\n').write('\n'.join(P))
print(f'{len(fns)} functions, {len(consts)} constants')

# The API reference.
SECTIONS = [('library', 'nm_version'), ('worlds', 'nm_world_create'), ('builds', 'nm_build_from_text'), ('agents', 'nm_agent_create'),
            ('the message table', 'nm_message_count'), ('sending messages', 'nm_msg_begin'), ('state and feedback', 'nm_agent_is_balancing'),
            ("the game's tasks", 'nm_agent_task_shot')]
A = ['# SDK API reference', '',
     f'{len(fns)} functions in `delirium_physics.dll` (crates/delirium-sdk; header `include/delirium_physics.h`). Generated by bindgen.py from src/lib.rs.',
     'Conventions (lib.rs): Z up, metres, kg, s; vectors float[3], rotations float[4] (x, y, z, w); 0 or a count on',
     'success, a negative `NM_E_*` on failure (`nm_last_error` says why); strings copied into (buf, len), returning the',
     'length the whole string needs. One thread per agent at a time.', '', '## Constants', '', '| name | value |', '|---|---|']
A += [f'| `{n}` | {v} |' for n, v in consts]
starts = {f: t for t, f in SECTIONS}
for n, args, ret, doc in fns:
    if n in starts:
        A += ['', f'## {starts[n][0].upper() + starts[n][1:]}', '']
    a = ', '.join(f'{ctype(t)} {an}' for an, t in args) or 'void'
    A.append(f'`{ctype(ret)} {n}({a})`')
    A.append('')
    if doc:
        A.append(doc)
        A.append('')
open(os.path.join(HERE, '..', '..', 'docs', 'nm', 'sdk-api.md'), 'w', newline=chr(10)).write(chr(10).join(A))
