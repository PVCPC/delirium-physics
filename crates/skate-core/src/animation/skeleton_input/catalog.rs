#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ScalarAttribute {
    pub name: &'static str,
    pub encoded_name: AttributeName,
    pub comparison_site: u32,
}
const fn entry(name: &'static str, comparison_site: u32) -> ScalarAttribute {
    ScalarAttribute {
        name,
        encoded_name: encode(name.as_bytes()),
        comparison_site,
    }
}
